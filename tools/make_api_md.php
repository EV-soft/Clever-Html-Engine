#  Makes php2html.api.md - a compact API reference for people and AI assistants - from the parameter comments in php2html.lib.php.
#  Run it after every change of the library (from the command line only):
#     php tools/make_api_md.php                      # writes php2html.api.md next to the library
#     php tools/make_api_md.php  other.lib.php  out.md
#  The library is read with the PHP tokenizer - never included (no side effects). Each parameter is documented as
#     $name = default,     # type: description          (more lines of the description: a line with only a # comment)
#  The comment line above a function is its description - "[Necessary basic element]" marks the core functions.

if (PHP_SAPI !== 'cli') { http_response_code(404);  exit; }
$lib= $argv[1] ?? dirname(__DIR__).'/php2html.lib.php';
$out= $argv[2] ?? dirname($lib).'/php2html.api.md';
$src= file_get_contents($lib);
if ($src === false) exit("Can not read $lib\n");
preg_match("/\\\$DocVer(?:File)?\s*=\s*'([^']+)'/", $src, $m);   $ver= $m[1] ?? '?';     // ($DocVerFile since 1.8.2)
$lines= explode("\n", str_replace("\r\n", "\n", $src));

$tok= token_get_all($src);
$cnt= count($tok);
$funcs= [];
$group= 'General';
for ($i= 0; $i < $cnt; $i++) {
    $t= $tok[$i];
    if (is_array($t) && $t[0] === T_COMMENT && preg_match('/##\s*Group\s*\*+\s*([^*]+?)\s*\*+/', $t[1], $g) && $g[1][0] !== '/')
        $group= rtrim(trim($g[1]), ':');
    if (!is_array($t) || $t[0] !== T_FUNCTION) continue;
    $j= $i + 1;  while ($j < $cnt && is_array($tok[$j]) && $tok[$j][0] === T_WHITESPACE) $j++;
    if (!is_array($tok[$j]) || $tok[$j][0] !== T_STRING) continue;           // A closure: fn() / function() {}
    $name= $tok[$j][1];  $line= $tok[$j][2];
    while ($j < $cnt && $tok[$j] !== '(') $j++;
    // The parameters: $var [= default] [# comment ...] up to the matching )
    $params= [];  $depth= 0;  $cur= null;  $inDef= false;  $sigComment= '';  $lastLine= $line;
    for ($k= $j; $k < $cnt; $k++) {
        $x= $tok[$k];
        $s= is_array($x) ? $x[1] : $x;
        if ($s === '(' || $s === '[') { $depth++;  if ($depth === 1 && $s === '(') continue; }
        if ($s === ')' || $s === ']') { $depth--;  if ($depth === 0) break; }
        if (is_array($x) && $x[0] === T_COMMENT) {
            $c= trim(preg_replace('/^(#|\/\/)\s?/', '', rtrim($x[1])));
            if ($cur === null && !$params) { $sigComment= $c;  continue; }        // The short form on the function line: "# labl:'', icon:''..."
            if (preg_match('/^\$\w+\s*=/', $c)) continue;                         // A parameter that is commented out: "# $foot='', ..."
            $p= &$params[count($params) - 1];
            $p['desc'].= ($p['desc'] > '' ? ' ' : '').$c;
            unset($p);
            $inDef= false;
            continue;
        }
        if ($depth === 1 && is_array($x) && $x[0] === T_VARIABLE) { $params[]= ['name' => substr($s, 1), 'def' => null, 'desc' => ''];  $cur= count($params) - 1;  $inDef= false;  continue; }
        if ($depth === 1 && $s === '=' && $cur !== null) { $inDef= true;  $params[$cur]['def']= '';  continue; }
        if ($depth === 1 && $s === ',') { $inDef= false;  continue; }
        if ($inDef && $cur !== null) $params[$cur]['def'].= is_array($x) && $x[0] === T_WHITESPACE ? ' ' : $s;
    }
    // The description: the comment line above - or a comment after the signature on the function line
    $desc= '';  $core= false;
    $above= trim($lines[$line - 2] ?? '');
    if (preg_match('/^#(?!#)\s*(.+)$/', $above, $d)) $desc= $d[1];
    if ($desc === '' && preg_match('/\)\s*(?:\{)?\s*(?:#+|\/\/)\s*(.+)$/', $lines[$line - 1], $d)) $desc= $d[1];
    if ($desc === '' && $sigComment > '' && preg_match('/\)\s*#+\s*(.+)$/', $sigComment, $d)) $desc= $d[1];
    if ($desc === '' && preg_match('/^\s*function\s+\w+\s*\(\s*(?:#|\/\/)?\s*\)?\s*(?:#+|\/\/)\s*(.+)$/', $lines[$line - 1], $d)) $desc= $d[1];
    if (stripos($desc, '[Necessary basic element]') !== false) { $core= true;  $desc= trim(str_ireplace('[Necessary basic element]', '', $desc)); }
    $desc= trim(preg_replace('/\s*\{\s*$/', '', $desc));
    $funcs[]= compact('name', 'line', 'group', 'params', 'desc', 'core');
}

// Only the public API in detail: htm_*, csrf_*, lang, the documented sys_* helpers - the rest is listed by name
$api= array_filter($funcs, fn($f) => preg_match('/^(htm_|csrf_|lang$|sys_|str_)/', $f['name']));
$rest= array_filter($funcs, fn($f) => !preg_match('/^(htm_|csrf_|lang$|sys_|str_)/', $f['name']));
$esc= fn($s) => str_replace(['|', "\n"], ['\|', ' '], (string)$s);

$md= "# php2html $ver - API reference\n\n".
"> Generated by `tools/make_api_md.php` from the parameter comments in `php2html.lib.php` - do not edit by hand, run the tool again.\n".
"> Written for people **and AI coding assistants**: read this file instead of the 500 KB library.\n\n".
"## Conventions\n\n".
"- **One file:** `require_once 'php2html.lib.php';` - no build step, no package manager. PHP 8.1+.\n".
"- **Call with named arguments** - always: `htm_Card_(capt:'@Settings', icon:'fas fa-sliders', clas:'cardW800');`.\n".
"  The order of the parameters has changed between versions (1.7); names are stable. An unknown name is a fatal error.\n".
"- **Parameter names are 4 characters** from a fixed vocabulary: `labl` label, `capt` caption, `hint` tooltip, `icon` Font Awesome class,\n".
"  `name` field name, `valu` value, `form` form id, `acti` action, `wdth` width, `vhgh` max height, `styl` style, `attr` attributes,\n".
"  `clas` CSS class, `kind` colour / purpose, `vrnt` variant, `list` options, `plho` placeholder, `rtrn` return instead of echo.\n".
"- **Output:** most `htm_*` functions **echo** their HTML. With `rtrn:true` they **return** it as a string instead.\n".
"  Functions without `rtrn` always echo (see the table).\n".
"- **Texts are translated:** a text that starts with `@` is a translation key - `'@Save'` is shown via `lang()` in the language of the session\n".
"  (`\$_SESSION['proglang']`, translations in `_trans.sys.json`). Texts without `@` are shown as they are.\n".
"- **Pairs:** `htm_Page_` ... `htm_Page_end`, `htm_Card_` ... `htm_Card_end`, `htm_Form_` ... `htm_Form_end`, `htm_Tabs_` / `htm_Tab` ... `htm_Tabs_end`,\n".
"  `htm_RowCol_` / `htm_RowCol_next` ... `htm_RowCol_end`, `htm_List_` / `htm_List_item` ... `htm_List_end`. Always close what you open.\n".
"- **Session:** the library starts the session (httponly, SameSite=Lax, secure on HTTPS) unless the page has started it already.\n".
"- **Forms and CSRF:** `htm_Card_(form:'f_x')` wraps the card body in a POST form **with the CSRF token**. In your own forms echo `csrf_field()`.\n".
"  **Every POST is checked when the library is included:** a missing or wrong token stops the request (HTTP 403, *CSRF-validating failed*)\n".
"  before your code runs - so the page needs no `csrf_verify()` of its own (calling it again does no harm).\n".
"- **POST from JavaScript:** `p2hPost(url, {id: 7}).then(r => r.json())` (every page of `htm_Page_` has it) sends the CSRF token along.\n".
"  A plain `fetch()` POST without the token gets 403.\n".
"- **Log in:** `htm_Login()` shows the form; `sys_login(hash:\$hash, pass:\$_POST['p2h_pass'])` checks it (a growing wait after wrong tries,\n".
"  for all browsers together) and returns '' when it is right; `sys_loginUser()` is '' when nobody is logged in; `sys_logout()`.\n".
"  Logins, failed and blocked tries and log-outs go to the activity log when `p2h_audit.inc.php` is included. A page behind the login:\n".
"  `if (!sys_loginRequired(link:'login.php')) exit;` - after the login `sys_redirect('', link: sys_loginBack('/'))` returns to that page.\n".
"  `htm_Login(list:[...])` lets the user choose what to log in to (posted as p2h_list) - **check on the server** that the user may open it.\n".
"- **Quotes:** `'` for PHP strings, `\"` for HTML attributes.\n\n".
"## Pitfalls\n\n".
"- **Several actions in one form:** give each `htm_AcceptButt` its own `valu:` (`valu:'save'`, `valu:'delete'`) and read `\$_POST['act']`\n".
"  (another name with `name:`). Without `valu` and `acti` the button gets `onclick='location.reload();'` - the form is still posted,\n".
"  but the button posts no value of its own.\n".
"- **After a POST** answer with `sys_redirect('@Saved')` - not with HTML: the page is loaded again with GET (a reload does not post again)\n".
"  and `htm_Page_` shows the message once (`htm_Flash`). An error: `sys_redirect('@Not saved', 'error')`.\n".
"- The library version is the constant `P2H_VERSION`. Since 1.8.2 the library leaves the page's own `\$DocVer`, `\$DocRev`, `\$DocFil` and `\$©`\n".
"  alone (1.8.1 and older overwrote them when included).\n".
"- No nested forms: a card with `form:` must not be inside another card with `form:`.\n".
"- A script that must accept a POST **without** a token (a webhook, a JSON API, a callback from another site) must not include the library -\n".
"  it would answer 403. Put such endpoints in their own file.\n".
"- Global settings are `\$gbl_*` variables (colours, card moving, flags, the program root) - set them **before** the require.\n\n".
"## A minimal page\n\n".
"```php\n<?php\nrequire_once __DIR__.'/php2html.lib.php';     // starts the session - and stops a POST without a valid CSRF token\n\nif (\$_SERVER['REQUEST_METHOD'] === 'POST') {\n".
"    if ((\$_POST['act'] ?? '') === 'save')  { /* ... save \$_POST['name'] ... */  sys_redirect('@Saved'); }\n".
"    if ((\$_POST['act'] ?? '') === 'reset') { /* ... */                         sys_redirect('@Reset', 'info'); }\n".
"    sys_redirect('@Unknown action', 'warning');                  // Post/Redirect/Get: the message is shown by htm_Page_\n}\n\n".
"htm_Page_(titl:'My page');\nhtm_Card_(capt:'@Settings', icon:'fas fa-sliders', form:'f_set', clas:'cardW800');\n    htm_Input(labl:'@Name', name:'name', valu:'', wdth:'300px');\n".
"    htm_AcceptButt(labl:'@Save',  icon:'fas fa-floppy-disk', kind:'save', form:'f_set', valu:'save');\n".
"    htm_AcceptButt(labl:'@Reset', icon:'fas fa-rotate-left', kind:'eras', form:'f_set', valu:'reset');\nhtm_Card_end();\nhtm_Page_end();\n```\n\n";

